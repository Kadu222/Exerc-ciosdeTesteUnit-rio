package exercicio1;

/**
 * Exercicio 1: metodo booleano que verifica se um numero e par.
 */
public class VerificadorParidade {

    /**
     * Retorna true se o numero passado como parametro for par
     * e false caso seja impar.
     */
    public boolean ehPar(int numero) {
        return numero % 2 == 0;
    }
}
